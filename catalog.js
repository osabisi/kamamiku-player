  return archive[show.id].trim().split("\n").map(row => {
    const [rawNumber, title, date, page, override] = row.split("|");
    const number = Number(rawNumber);
    const id = show.prefix + rawNumber.padStart(3, "0");
    const label = rawNumber.padStart(["orig", "gold"].includes(show.id) ? 3 : 2, "0");
    let audioName = show.prefix + rawNumber.padStart(2, "0");
    if (show.id === "orig") audioName = label;
    if (show.id === "love") audioName = "l" + rawNumber;
    const parts = override === "video" ? [] : multiPart[id] ?? [["本編", override ?? audioName + "/" + audioName + ".mp3"]];
    const tracks = parts.map(([name, path], index) => ({ id: id + ":" + index, name, url: audioOrigin + path }));
    const article = articleOrigin + (page.includes("/") ? page : "radio/" + page) + "/";
    return { id, show, number, label, title, date, article, tracks };
  });
